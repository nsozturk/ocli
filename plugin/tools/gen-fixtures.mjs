// Usage: node plugin/tools/gen-fixtures.mjs <normalized live .jsonl of a real run>
// Builds plugin/hooks/fixtures.ts from the repo's raw CLI captures, through the
// real normalize() and the same envelope dispatch.mjs writes, plus the given live file SCRUBBED: only
// its shape is kept (kinds, seq, timing, tools, token counts, statuses). Ids, task, pid, every tool
// detail and every message text are replaced, so no path, branch, commit or brief of the private run
// can reach the fixture. The script refuses to write if a machine path survives anyway.
import { readFileSync, writeFileSync } from 'node:fs';
import { normalize } from '../../dispatcher/events.mjs';

const root = new URL('../../', import.meta.url);
const models = { codex: 'gpt-5.6-luna', opencode: 'zai-coding-plan/glm-5.3', agy: 'gemini-3.8-flash-medium', muse: 'muse' };
const out = {};
for (const cli of Object.keys(models)) {
  const raw = readFileSync(new URL(`tests/fixtures/orchestra-events/${cli}.jsonl`, root), 'utf8').split('\n').filter(Boolean);
  const runId = `fixture-${cli}`;
  const state = { dropped: Object.create(null) };
  let seq = 0;
  let t = Date.parse('2026-10-10T12:00:00.000Z');
  const lines = [];
  const emit = event => lines.push(JSON.stringify({ v: 1, runId, seq: seq++, at: new Date(t += 1000).toISOString(), task: 'fixture-task', role: 'implement', cli, ...event }));
  emit({ kind: 'run.start', model: models[cli], root: '/home/user/repo', parentId: null, pid: 1 });
  for (const line of raw) for (const event of normalize(cli, line, state)) emit(event);
  emit({ kind: 'run.end', exitCode: 0, signal: null, ms: seq * 1000, status: 'completed', nodeId: null, score: null, dropped: { ...state.dropped } });
  out[cli] = lines;
}
const LIVE = { runId: '00000000-0000-4000-8000-0000000000a1', task: 'glm-live' };
const tools = Object.create(null);
const scrub = line => {
  const e = JSON.parse(line);
  const out = { v: e.v, runId: LIVE.runId, seq: e.seq, at: e.at, task: LIVE.task, role: e.role, cli: e.cli, kind: e.kind };
  switch (e.kind) {
    case 'run.start': return { ...out, model: e.model, root: '/home/user/repo', parentId: null, pid: 1 };
    case 'step': return { ...out, label: /^[a-z_.]+( [a-z]+=\S+)*$/.test(e.label) ? e.label : 'step' };
    case 'tool.start': case 'tool.end': {
      tools[e.tool] = (tools[e.tool] ?? 0) + 1;
      return { ...out, tool: e.tool, detail: `${e.tool} call ${tools[e.tool]}`, ...(e.kind === 'tool.end' ? { ok: e.ok } : {}) };
    }
    case 'usage': return { ...out, input: e.input, output: e.output, cached: e.cached, reasoning: e.reasoning };
    case 'message': return { ...out, text: `progress note ${e.seq}` };
    case 'warn': return { ...out, text: 'warning' };
    case 'run.end': return { ...out, exitCode: e.exitCode, signal: e.signal, ms: e.ms, status: e.status, nodeId: null, score: e.score, dropped: e.dropped };
    default: return out;
  }
};
const live = readFileSync(process.argv[2], 'utf8').split('\n').filter(Boolean).map(line => JSON.stringify(scrub(line)));
const leak = live.find(l => /\/(?:Users|home\/(?!user\/)|var\/folders|private|tmp)\//.test(l));
if (leak) throw new Error(`machine path survived the scrub: ${leak.slice(0, 200)}`);
let ts = '// Generated by tools/gen-fixtures.mjs: each raw capture in tests/fixtures/orchestra-events/\n'
  + '// run through the real normalize() of dispatcher/events.mjs inside the envelope dispatch.mjs writes.\n'
  + '// GLM_LIVE is the shape of a real opencode/GLM live file (timing, tools, tokens, statuses) with every\n'
  + '// id, path, tool detail and message text replaced.\n'
  + '// The plugin test environment has no Node, so normalize cannot be imported there.\n\n';
for (const [cli, lines] of Object.entries(out)) ts += `export const ${cli.toUpperCase()}: string[] = ${JSON.stringify(lines, null, 1)}\n\n`;
ts += `export const GLM_LIVE: string[] = ${JSON.stringify(live, null, 1)}\n`;
writeFileSync(new URL('plugin/hooks/fixtures.ts', root), ts);
for (const [k, v] of Object.entries(out)) console.log(k, v.length, 'events; dropped', JSON.parse(v.at(-1)).dropped);
console.log('GLM_LIVE', live.length, 'lines, scrubbed');
